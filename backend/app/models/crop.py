"""
Crop and CropGrowthStage models.

Crop stores validated agronomic constants (Kc coefficients, root depth,
depletion thresholds) derived from FAO-56 and published literature.

CropGrowthStage tracks which FAO-56 growth stage a zone is currently in,
enabling stage-appropriate Kc values for ET₀ → ETc calculation.
"""

from __future__ import annotations

from datetime import date
from typing import TYPE_CHECKING

from sqlalchemy import Date, Float, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.engine import Base
from app.models.base import TimestampMixin

if TYPE_CHECKING:
    from app.models.zone import Zone


class Crop(Base, TimestampMixin):
    """
    Validated agronomic constants for a crop species.

    All Kc values are sourced from FAO-56 (Allen et al., 1998) or
    peer-reviewed agronomic literature. They are NEVER generated by an LLM.

    FAO-56 Growth Stages:
    1. Initial (Ini)   — from sowing to ~10% ground cover
    2. Crop Development (Dev) — from 10% to effective full cover
    3. Mid-Season (Mid) — from full cover to start of maturity
    4. Late Season (Late) — from start of maturity to harvest

    Attributes
    ----------
    id : int
        Primary key.
    name : str
        Crop common name (e.g. "Wheat", "Rice", "Maize").
    scientific_name : str | None
        Botanical name.
    crop_type : str | None
        "cereal", "vegetable", "fruit", "legume", "oilseed", etc.
    kc_initial : float
        FAO-56 crop coefficient — initial stage.
    kc_mid : float
        FAO-56 crop coefficient — mid-season (peak).
    kc_end : float
        FAO-56 crop coefficient — late season / harvest.
    root_depth_initial_m : float
        Root zone depth at initial stage in metres.
    root_depth_max_m : float
        Maximum root zone depth in metres.
    depletion_fraction_p : float
        FAO-56 allowable soil water depletion fraction (p). Typical: 0.5.
    days_initial : int
        Typical duration of initial stage in days.
    days_development : int
        Typical duration of crop development stage in days.
    days_mid : int
        Typical duration of mid-season stage in days.
    days_late : int
        Typical duration of late-season stage in days.
    total_growing_days : int
        Total season length in days.
    reference : str | None
        Citation for the agronomic constants (e.g. "FAO-56 Table 12").
    notes : str | None
        Free-text notes.
    """

    __tablename__ = "crops"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    name: Mapped[str] = mapped_column(String(150), nullable=False, unique=True, index=True)
    scientific_name: Mapped[str | None] = mapped_column(String(200))
    crop_type: Mapped[str | None] = mapped_column(String(50))

    # FAO-56 Kc coefficients (dimensionless)
    kc_initial: Mapped[float] = mapped_column(Float, nullable=False, default=0.3)
    kc_mid: Mapped[float] = mapped_column(Float, nullable=False, default=1.0)
    kc_end: Mapped[float] = mapped_column(Float, nullable=False, default=0.4)

    # Root depth (metres)
    root_depth_initial_m: Mapped[float] = mapped_column(Float, nullable=False, default=0.15)
    root_depth_max_m: Mapped[float] = mapped_column(Float, nullable=False, default=0.60)

    # Soil water depletion fraction (FAO-56 p)
    depletion_fraction_p: Mapped[float] = mapped_column(Float, nullable=False, default=0.5)

    # Stage durations (days)
    days_initial: Mapped[int] = mapped_column(Integer, nullable=False, default=20)
    days_development: Mapped[int] = mapped_column(Integer, nullable=False, default=35)
    days_mid: Mapped[int] = mapped_column(Integer, nullable=False, default=40)
    days_late: Mapped[int] = mapped_column(Integer, nullable=False, default=25)
    total_growing_days: Mapped[int] = mapped_column(Integer, nullable=False, default=120)

    reference: Mapped[str | None] = mapped_column(String(500))
    notes: Mapped[str | None] = mapped_column(Text)

    # Relationships
    growth_stages: Mapped[list["CropGrowthStage"]] = relationship(
        "CropGrowthStage", back_populates="crop", cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return (
            f"<Crop id={self.id} name={self.name!r} "
            f"Kc=[{self.kc_initial}/{self.kc_mid}/{self.kc_end}]>"
        )


class CropGrowthStage(Base, TimestampMixin):
    """
    Tracks the current FAO-56 growth stage for a crop in a zone.

    This is updated by the CropAgent as the crop progresses through
    its growing season. The IrrigationDecisionAgent reads the current
    stage to select the correct Kc coefficient for ETc computation.

    Attributes
    ----------
    id : int
        Primary key.
    zone_id : int
        FK → zones.id.
    crop_id : int
        FK → crops.id.
    stage_name : str
        "initial", "development", "mid", "late", "harvest".
    planting_date : date
        Date when the crop was sown / transplanted.
    days_after_planting : int
        Number of days elapsed since planting_date.
    current_kc : float
        Interpolated Kc for the current day within the stage.
    current_root_depth_m : float
        Interpolated root depth in metres for the current day.
    notes : str | None
        Free-text notes.
    """

    __tablename__ = "crop_growth_stages"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    zone_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("zones.id", ondelete="CASCADE"), nullable=False, index=True
    )
    crop_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("crops.id", ondelete="CASCADE"), nullable=False, index=True
    )
    stage_name: Mapped[str] = mapped_column(String(50), nullable=False)
    planting_date: Mapped[date] = mapped_column(Date, nullable=False)
    days_after_planting: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    current_kc: Mapped[float] = mapped_column(Float, nullable=False)
    current_root_depth_m: Mapped[float] = mapped_column(Float, nullable=False)
    notes: Mapped[str | None] = mapped_column(Text)

    # Relationships
    zone: Mapped["Zone"] = relationship("Zone", back_populates="growth_stages")
    crop: Mapped["Crop"] = relationship("Crop", back_populates="growth_stages")

    def __repr__(self) -> str:
        return (
            f"<CropGrowthStage id={self.id} zone_id={self.zone_id} "
            f"stage={self.stage_name!r} Kc={self.current_kc}>"
        )
